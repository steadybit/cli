// Command unordered lists the fields of each schema in the platform spec that hold a set:
// lists marked `uniqueItems`, which the platform keeps in a Java Set and returns in an
// order of its own. `diff` compares those without regard to order. It runs with
// `go generate ./api`, so a set added to the platform is picked up with the spec.
//
//	go run ./internal/tools/unordered <spec> <output>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"slices"
	"sort"
	"strings"
)

type schema struct {
	Ref                  string             `json:"$ref"`
	Type                 string             `json:"type"`
	UniqueItems          bool               `json:"uniqueItems"`
	Items                *schema            `json:"items"`
	Properties           map[string]*schema `json:"properties"`
	AdditionalProperties json.RawMessage    `json:"additionalProperties"`
	AllOf                []*schema          `json:"allOf"`
	OneOf                []*schema          `json:"oneOf"`
	AnyOf                []*schema          `json:"anyOf"`
	Discriminator        *struct {
		Mapping map[string]string `json:"mapping"`
	} `json:"discriminator"`
}

type spec struct {
	Components struct {
		Schemas map[string]*schema `json:"schemas"`
	} `json:"components"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run ./internal/tools/unordered <spec> <output>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(specFile, output string) error {
	raw, err := os.ReadFile(specFile)
	if err != nil {
		return err
	}
	var s spec
	if err := json.Unmarshal(raw, &s); err != nil {
		return fmt.Errorf("%s: %w", specFile, err)
	}
	schemas := s.Components.Schemas
	names := make([]string, 0, len(schemas))
	for name := range schemas {
		names = append(names, name)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/tools/unordered from the platform spec. DO NOT EDIT.

package api

// Unordered names, by schema, the fields holding a set: the platform keeps them in no
// order of its own. A path goes into every item of the lists on its way, and "*" into
// every value of a map.
var Unordered = map[string][]string{
`)
	for _, name := range names {
		w := walker{schemas: schemas, seen: map[string]bool{name: true}}
		w.walk(schemas[name], "")
		if len(w.paths) == 0 {
			continue
		}
		sort.Strings(w.paths)
		fmt.Fprintf(&b, "\t%q: {", name)
		for i, p := range slices.Compact(w.paths) {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", p)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(output, src, 0o644)
}

type walker struct {
	schemas map[string]*schema
	seen    map[string]bool
	paths   []string
}

// walk follows references once each per path, so recursive schemas end.
func (w *walker) walk(s *schema, path string) {
	if s == nil {
		return
	}
	if s.Ref != "" {
		w.ref(s.Ref, path)
		return
	}
	for _, list := range [][]*schema{s.AllOf, s.OneOf, s.AnyOf} {
		for _, sub := range list {
			w.walk(sub, path)
		}
	}
	if s.Discriminator != nil {
		for _, ref := range s.Discriminator.Mapping {
			w.ref(ref, path)
		}
	}
	if s.Type == "array" {
		if s.UniqueItems {
			w.paths = append(w.paths, path)
		}
		w.walk(s.Items, path)
	}
	for name, p := range s.Properties {
		w.walk(p, join(path, name))
	}
	if len(s.AdditionalProperties) > 0 && s.AdditionalProperties[0] == '{' {
		var values schema
		if json.Unmarshal(s.AdditionalProperties, &values) == nil {
			w.walk(&values, join(path, "*"))
		}
	}
}

func (w *walker) ref(ref, path string) {
	name := strings.TrimPrefix(ref, "#/components/schemas/")
	if w.seen[name] {
		return
	}
	w.seen[name] = true
	w.walk(w.schemas[name], path)
	delete(w.seen, name)
}

func join(path, name string) string {
	if path == "" {
		return name
	}
	return path + "." + name
}
